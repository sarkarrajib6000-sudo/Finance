/**
 * Generator helper function to build random employee records
 */
export function generateRandomEmployee(indexOffset: number = 0): Employee {
  const firstNames = ['Arjun', 'Diya', 'Nikhil', 'Tanvi', 'Rajesh', 'Sanya', 'Yash', 'Pooja', 'Varun', 'Rhea'];
  const lastNames = ['Kapoor', 'Deshmukh', 'Singhania', 'Bhatia', 'Pillai', 'Chawla', 'Kulkarni', 'Bansal', 'Tripathi', 'Dutta'];
  const departments = ['Engineering', 'Product', 'Design', 'Sales', 'Marketing', 'Finance', 'Human Resources', 'Operations'];
  const designations: Record<string, string[]> = {
    Engineering: ['Software Engineer', 'Senior Backend Developer', 'Frontend Specialist', 'DevOps Specialist'],
    Product: ['Product Associate', 'Technical Product Manager'],
    Design: ['UI/UX Specialist', 'Visual Designer'],
    Sales: ['Account Executive', 'Sales Development Rep'],
    Marketing: ['Growth Marketer', 'SEO Specialist'],
    Finance: ['Financial Analyst', 'Senior Auditor'],
    'Human Resources': ['HR Specialist', 'Talent Acquisition Partner'],
    Operations: ['Operations Lead', 'Logistics Coordinator'],
  };
  const bankNames = [
    { ifsc: 'HDFC0001234', prefix: '918234' },
    { ifsc: 'ICIC0005678', prefix: '918235' },
    { ifsc: 'SBIN0009999', prefix: '918236' },
    { ifsc: 'UTIB0002233', prefix: '918237' },
  ];

  const fn = firstNames[Math.floor(Math.random() * firstNames.length)]!;
  const ln = lastNames[Math.floor(Math.random() * lastNames.length)]!;
  const dept = departments[Math.floor(Math.random() * departments.length)]!;
  const desigList = designations[dept] || ['Specialist'];
  const desig = desigList[Math.floor(Math.random() * desigList.length)]!;
  const bank = bankNames[Math.floor(Math.random() * bankNames.length)]!;
  const numId = 15 + indexOffset;

  const basic = Math.floor(Math.random() * 60 + 35) * 1000;
  const hra = Math.round(basic * 0.4);
  const allowances = Math.round(basic * 0.15);

  const letters = 'ABCDEFGHIJKLMNOPQRSTUVWXYZ';
  const pan = `${letters[Math.floor(Math.random() * 26)]}${letters[Math.floor(Math.random() * 26)]}${letters[Math.floor(Math.random() * 26)]}P${letters[Math.floor(Math.random() * 26)]}${Math.floor(1000 + Math.random() * 9000)}${letters[Math.floor(Math.random() * 26)]}`;

  return {
    id: `emp-${numId}`,
    name: `${fn} ${ln}`,
    employeeCode: `EMP-${numId.toString().padStart(3, '0')}`,
    email: `${fn.toLowerCase()}.${ln.toLowerCase()}@example.com`,
    phone: `+91 ${Math.floor(70000 + Math.random() * 29999)} ${Math.floor(10000 + Math.random() * 89999)}`,
    department: dept,
    designation: desig,
    basicSalary: basic,
    hra: hra,
    allowances: allowances,
    bankAccount: `${bank.prefix}${Math.floor(10000000 + Math.random() * 89999999)}`,
    bankIFSC: bank.ifsc,
    panNumber: pan,
    dateOfJoining: `2024-0${Math.floor(1 + Math.random() * 8)}-${Math.floor(10 + Math.random() * 18)}`,
    isActive: true,
    createdAt: new Date().toISOString(),
  };
}
